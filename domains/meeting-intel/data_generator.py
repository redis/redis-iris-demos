def build_dataset() -> dict[str, list[dict[str, Any]]]:
    seed = _load("seed", "seed.py")
    transcripts_mod = _load("transcripts", "transcripts.py")
    meetings = [dict(r) for r in seed.MEETINGS]
    transcripts = [dict(r) for r in transcripts_mod.TRANSCRIPTS]
    decisions = [dict(r) for r in seed.DECISIONS]
    risks = [dict(r) for r in seed.RISKS]
    _with_embeddings(meetings, transcripts, decisions, risks)
    return {
        "Person": list(seed.PEOPLE),
        "Project": list(seed.PROJECTS),
        "Meeting": meetings,
        "MeetingParticipant": _participants(seed.ATTENDEES),
        "TranscriptSegment": transcripts,
        "Decision": decisions,
        "ActionItem": list(seed.ACTIONS),
        "Risk": risks,
        "ProjectDependency": list(seed.DEPENDENCIES),
        "Agenda": list(seed.AGENDAS),
    }


def generate_demo_data(*, output_dir: Path, seed: int | None = None, update_env_file: bool = False) -> GeneratedDataset:
    del seed
    dataset = build_dataset()
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    for class_name, file_name in FILE_MAP.items():
        _write_jsonl(output_dir / file_name, dataset[class_name])

    SQL_DIR.mkdir(parents=True, exist_ok=True)
    (SQL_DIR / "01-seed.sql").write_text(_seed_sql(dataset), encoding="utf-8")
    extra_dir = SQL_DIR / "extra"
    extra_dir.mkdir(parents=True, exist_ok=True)
    (extra_dir / "transcript-05.sql").write_text(extra_transcript_sql(), encoding="utf-8")

    # Always return identity env updates. scripts/generate_data.py writes them
    # when invoked; tests pass update_env_file=False so they do not touch .env.
    del update_env_file
    env_updates = {
        "DEMO_USER_ID": "person-maya",
        "DEMO_USER_NAME": "Maya Chen",
        "DEMO_USER_EMAIL": "maya.chen@harborline.example",
        "DEMO_USER_ROLE": "team",
        "DEMO_DOMAIN": "meeting-intel",
    }

    summary = {key: len(rows) for key, rows in dataset.items()}
    return GeneratedDataset(output_dir=str(output_dir), env_updates=env_updates, summary=summary)


if __name__ == "__main__":
    generate_demo_data(output_dir=ROOT / "output" / "meeting-intel", update_env_file=True)
